"""Build the Kaggle kernel for encoder inference (Chunk 4).

    python scripts/build_kaggle_encoder.py --dataset ntllm-encoder-v1 --mode submit
    python scripts/build_kaggle_encoder.py --dataset ntllm-encoder-v1 --mode timing   # dummy 4,000 rows

Writes notebooks/kaggle_encoder_<mode>/ with kernel.py + kernel-metadata.json (GPU on,
internet off, the weights dataset attached). The kernel reads ntllm.json next to the
weights: if the model was trained with the gzip family prefix, it rebuilds the gzip index
from the train-split rows (prompt ids inlined) and prefixes test texts the same way.

Run it locally first (CPU works, slowly):
    NTLLM_INPUT=<dir with train.csv, test.csv and the weights folder> NTLLM_OUTPUT=/tmp/out \\
        python notebooks/kaggle_encoder_submit/kernel.py
Push (needs Dom's OK): kaggle kernels push -p notebooks/kaggle_encoder_<mode>
"""
import argparse
import json

from ntllm.data.load import LABELS
from ntllm.data.splits import load_split
from ntllm.paths import ROOT

KAGGLE_USER = "dominictedrow"
COMPETITION = "name-that-llm"

MAIN = r'''

# ---------------------------------------------------------------- kernel main
import glob
import json
import os
import time

import torch
from transformers import AutoModelForSequenceClassification, AutoTokenizer

INPUT = os.environ.get("NTLLM_INPUT", "/kaggle/input")
OUTPUT = os.environ.get("NTLLM_OUTPUT", "/kaggle/working")


def find(name):
    hits = sorted(glob.glob(os.path.join(INPUT, "**", name), recursive=True))
    assert hits, f"{name} not found under {INPUT}"
    return hits[0]


@torch.no_grad()
def predict_logits(model, tok, texts, device, max_len, batch_size=64):
    order = np.argsort([len(t) for t in texts])  # length-sorted batches: less padding
    out = np.empty((len(texts), len(LABELS)), dtype=np.float32)
    for i in range(0, len(texts), batch_size):
        idx = order[i:i + batch_size]
        enc = tok([texts[j] for j in idx], truncation=True, max_length=max_len,
                  padding=True, return_tensors="pt").to(device)
        with torch.autocast("cuda", dtype=torch.bfloat16, enabled=device.type == "cuda"):
            out[idx] = model(**enc).logits.float().cpu().numpy()
    return out


def main():
    t0 = time.time()
    model_dir = os.path.dirname(find("ntllm.json"))
    meta = json.load(open(os.path.join(model_dir, "ntllm.json")))
    assert meta["labels"] == LABELS, "label order differs from training"
    full = pd.read_csv(find("train.csv"))
    train = full[full.prompt_id.isin(TRAIN_PROMPTS)].assign(split="train").reset_index(drop=True)
    assert train.prompt_id.nunique() == len(TRAIN_PROMPTS)

    if MODE == "timing":
        pool = full[~full.id.isin(train.id)]
        test = pool.sample(n=DUMMY_ROWS, replace=True, random_state=0)[["text"]].reset_index(drop=True)
        test.insert(0, "id", [f"dummy{i:05d}" for i in range(len(test))])
    else:
        test = pd.read_csv(find("test.csv"))
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"mode={MODE} device={device} backbone={meta['backbone']} family={meta.get('family')} "
          f"test={len(test)}", flush=True)

    texts = test.text.tolist()
    if meta.get("family"):
        t = time.time()
        gf = GzipFamily(k=meta.get("family_k", 7)).fit(train)
        texts = add_prefix(texts, gf.predict(test[["text"]]))
        print(f"gzip family prefix: {time.time() - t:.1f}s", flush=True)

    tok = AutoTokenizer.from_pretrained(model_dir)
    model = AutoModelForSequenceClassification.from_pretrained(model_dir, dtype=torch.float32).to(device).eval()
    t1 = time.time()
    logits = predict_logits(model, tok, texts, device, meta["max_len"])
    t2 = time.time()

    sub = pd.DataFrame({"id": test.id, "model": np.array(LABELS)[logits.argmax(1)]})
    assert sub.id.is_unique and set(sub.id) == set(test.id)
    name = "submission.parquet" if MODE == "submit" else "timing_submission.parquet"
    os.makedirs(OUTPUT, exist_ok=True)
    sub.to_parquet(os.path.join(OUTPUT, name), index=False)
    np.save(os.path.join(OUTPUT, "encoder_logits.npy"), logits)

    per_row = (t2 - t1) / max(len(test), 1)
    print(f"predict {t2 - t1:.1f}s ({per_row * 1000:.1f} ms/row)  total {time.time() - t0:.1f}s", flush=True)
    print(f"projected for 4,000 rows: {per_row * 4000 / 60:.1f} min + setup (limit 540 min)", flush=True)
    print(f"wrote {name}: {len(sub)} rows, {sub.model.nunique()} labels predicted", flush=True)


if __name__ == "__main__":
    main()
'''


def inline(path) -> str:
    lines = (ROOT / path).read_text().splitlines()
    return "\n".join(l for l in lines if not l.startswith("from ntllm")) + "\n"


def build(mode: str, dummy_rows: int) -> str:
    train_prompts = sorted(load_split("train").prompt_id.unique())
    head = (f"# AUTO-GENERATED by scripts/build_kaggle_encoder.py; do not edit by hand.\n"
            f"# ntllm encoder inference kernel, mode={mode} (splits v1).\n\n"
            f"import numpy as np\nimport pandas as pd\n\nLABELS = {LABELS!r}\n\n")
    consts = (f"\n\n# ---------------------------------------------------------------- config\n"
              f"MODE = {mode!r}\nDUMMY_ROWS = {dummy_rows}\nTRAIN_PROMPTS = {train_prompts!r}\n")
    return (head
            + "# ---------------------------------------------------------------- ntllm/models/gzip_knn.py\n"
            + inline("ntllm/models/gzip_knn.py")
            + "\n# ---------------------------------------------------------------- ntllm/features/family.py\n"
            + inline("ntllm/features/family.py") + consts + MAIN)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--dataset", required=True, help="weights dataset slug (scripts/export_encoder.py)")
    ap.add_argument("--mode", choices=["timing", "submit"], default="submit")
    ap.add_argument("--dummy-rows", type=int, default=4000)
    a = ap.parse_args()

    out = ROOT / "notebooks" / f"kaggle_encoder_{a.mode}"
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(build(a.mode, a.dummy_rows))
    slug = f"ntllm-encoder-{a.mode}"
    meta = {
        "id": f"{KAGGLE_USER}/{slug}", "title": slug, "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": True, "enable_internet": False,
        "dataset_sources": [f"{KAGGLE_USER}/{a.dataset}"], "competition_sources": [COMPETITION],
        "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {out}/kernel.py + kernel-metadata.json  (kaggle id {meta['id']}, dataset {a.dataset})")


if __name__ == "__main__":
    main()
