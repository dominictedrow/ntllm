"""Build the self-contained Kaggle kernel for TF-IDF + linear SVM.

    python scripts/build_kaggle_svm.py --mode timing                  # dummy 4,000-row test
    python scripts/build_kaggle_svm.py --mode submit --C 0.3 --min-prompts 3

Writes notebooks/kaggle_svm_<mode>/ with kernel.py + kernel-metadata.json.
kernel.py inlines ntllm/features/tfidf.py + ntllm/models/linear.py and the train-split prompt
ids, so the kernel needs only the competition data (no dataset upload, internet off).
It fits on the train split only (design: base models see only train), in a few seconds.

Run it locally first:
    NTLLM_INPUT=data/raw NTLLM_OUTPUT=/tmp/out python notebooks/kaggle_svm_submit/kernel.py
Push (needs Dom's OK):
    kaggle kernels push -p notebooks/kaggle_svm_<mode>
"""
import argparse
import json

from ntllm.data.load import LABELS
from ntllm.data.splits import load_split
from ntllm.paths import ROOT

KAGGLE_USER = "dominictedrow"
COMPETITION = "name-that-llm"

MAIN = r'''

# ---------------------------------------------------------------- kernel main
import glob
import os
import time


INPUT = os.environ.get("NTLLM_INPUT", "/kaggle/input")
OUTPUT = os.environ.get("NTLLM_OUTPUT", "/kaggle/working")


def find(name):
    hits = sorted(glob.glob(os.path.join(INPUT, "**", name), recursive=True))
    assert hits, f"{name} not found under {INPUT}"
    return hits[0]


def main():
    t0 = time.time()
    full = pd.read_csv(find("train.csv"))
    train = full[full.prompt_id.isin(TRAIN_PROMPTS)] if FIT_ON == "train" else full
    assert FIT_ON == "all" or train.prompt_id.nunique() == len(TRAIN_PROMPTS)
    train = train.assign(split="train").reset_index(drop=True)

    if MODE == "timing":
        # Dummy test the size of the hidden one, drawn from passages outside the fit set.
        pool = full[~full.id.isin(train.id)] if FIT_ON == "train" else full
        test = pool.sample(n=DUMMY_ROWS, replace=True, random_state=0)[["text"]].reset_index(drop=True)
        test.insert(0, "id", [f"dummy{i:05d}" for i in range(len(test))])
    else:
        test = pd.read_csv(find("test.csv"))
    print(f"mode={MODE} fit_on={FIT_ON} C={C} min_prompts={MIN_PROMPTS} cpus={os.cpu_count()} "
          f"train={len(train)} test={len(test)}", flush=True)

    feats = TfidfFeatures(**FEATURES).fit(train)
    model = make_model("svm", C=C).fit(feats.transform(train.text), train.model)
    print(f"vocab: {feats.stats_}", flush=True)
    t1 = time.time()
    preds = model.predict(feats.transform(test.text))
    t2 = time.time()

    sub = pd.DataFrame({"id": test.id, "model": preds})
    assert sub.id.is_unique and set(sub.id) == set(test.id)
    assert set(sub.model) <= set(LABELS), set(sub.model) - set(LABELS)
    name = "submission.parquet" if MODE == "submit" else "timing_submission.parquet"
    os.makedirs(OUTPUT, exist_ok=True)
    sub.to_parquet(os.path.join(OUTPUT, name), index=False)

    per_row = (t2 - t1) / max(len(test), 1)
    print(f"fit {t1 - t0:.1f}s  predict {t2 - t1:.1f}s  ({per_row * 1000:.2f} ms/row)  "
          f"total {time.time() - t0:.1f}s", flush=True)
    print(f"projected for 4,000 rows: {per_row * 4000 / 60:.2f} min (limit 540 min)", flush=True)
    print(f"wrote {name}: {len(sub)} rows, {sub.model.nunique()} labels predicted", flush=True)


if __name__ == "__main__":
    main()
'''


def inline(path) -> str:
    """Module source minus its ntllm imports (the kernel defines LABELS itself)."""
    lines = (ROOT / path).read_text().splitlines()
    return "\n".join(l for l in lines if not l.startswith("from ntllm")) + "\n"


def build(mode: str, C: float, min_prompts: int, fit_on: str, dummy_rows: int) -> str:
    train_prompts = sorted(load_split("train").prompt_id.unique())
    features = dict(analyzer="both", word_ngram=[1, 2], char_ngram=[2, 5], min_df=2,
                    max_features=None, lowercase=False, min_prompts=min_prompts)
    head = (
        f"# AUTO-GENERATED by scripts/build_kaggle_svm.py; do not edit by hand.\n"
        f"# ntllm TF-IDF + linear SVM kernel, mode={mode}. Fit set: {fit_on} (splits v1).\n\n"
        f"import pandas as pd\n\n"
        f"LABELS = {LABELS!r}\n\n"
    )
    consts = (
        f"\n\n# ---------------------------------------------------------------- config\n"
        f"MODE = {mode!r}\nFIT_ON = {fit_on!r}\nC = {C}\nMIN_PROMPTS = {min_prompts}\n"
        f"FEATURES = {features!r}\nDUMMY_ROWS = {dummy_rows}\n"
        f"TRAIN_PROMPTS = {train_prompts!r}\n"
    )
    return (head + "# ---------------------------------------------------------------- ntllm/features/tfidf.py\n"
            + inline("ntllm/features/tfidf.py")
            + "\n# ---------------------------------------------------------------- ntllm/models/linear.py\n"
            + inline("ntllm/models/linear.py") + consts + MAIN)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--mode", choices=["timing", "submit"], required=True)
    ap.add_argument("--C", type=float, default=0.3)
    ap.add_argument("--min-prompts", type=int, default=3)
    ap.add_argument("--fit-on", choices=["train", "all"], default="train",
                    help="train = train split only (design); all = every train.csv row")
    ap.add_argument("--dummy-rows", type=int, default=4000)
    a = ap.parse_args()

    out = ROOT / "notebooks" / f"kaggle_svm_{a.mode}"
    out.mkdir(parents=True, exist_ok=True)
    (out / "kernel.py").write_text(build(a.mode, a.C, a.min_prompts, a.fit_on, a.dummy_rows))
    slug = f"ntllm-tfidf-svm-{a.mode}"
    meta = {
        "id": f"{KAGGLE_USER}/{slug}", "title": slug, "code_file": "kernel.py",
        "language": "python", "kernel_type": "script", "is_private": True,
        "enable_gpu": False, "enable_internet": False,
        "dataset_sources": [], "competition_sources": [COMPETITION], "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"wrote {out}/kernel.py + kernel-metadata.json  (kaggle id {meta['id']})")


if __name__ == "__main__":
    main()
